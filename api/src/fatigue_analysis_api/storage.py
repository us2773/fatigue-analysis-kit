"""Private upload storage, independent of HTTP and analysis libraries."""

import os
from pathlib import Path
from uuid import UUID


class UploadError(Exception):
    def __init__(self, code: str, message: str, http_status: int = 400):
        super().__init__(message)
        self.code = code
        self.http_status = http_status


class VideoStore:
    def __init__(self, data_dir: Path, max_bytes: int):
        self.directory = data_dir / "01_raw" / "movie"
        self.max_bytes = max_bytes

    def begin(self, analysis_id: str, extension: str) -> "PendingVideo":
        # Paths are generated by the server, never taken from a client filename.
        safe_id = UUID(analysis_id).hex
        if extension not in {".mp4", ".mov"}:
            raise ValueError("Unsupported storage extension")
        self.directory.mkdir(parents=True, exist_ok=True, mode=0o700)
        return PendingVideo(self.directory / f"{safe_id}{extension}", self.max_bytes)


class PendingVideo:
    def __init__(self, path: Path, max_bytes: int):
        self.path = path
        self.partial_path = path.with_suffix(path.suffix + ".part")
        self.max_bytes = max_bytes
        self.size = 0
        self._file = None

    def __enter__(self) -> "PendingVideo":
        fd = os.open(self.partial_path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        self._file = os.fdopen(fd, "wb")
        return self

    def write(self, chunk: bytes) -> None:
        if self.size + len(chunk) > self.max_bytes:
            raise UploadError("VIDEO_TOO_LARGE", "動画の容量が上限を超えています。", 413)
        self._file.write(chunk)
        self.size += len(chunk)

    def finish(self) -> Path:
        if not self.size:
            raise UploadError("EMPTY_VIDEO", "動画データが空です。")
        self._file.close()
        # Hard-link creation fails if the destination exists: no silent overwrite.
        os.link(self.partial_path, self.path)
        self.partial_path.unlink()
        return self.path

    def __exit__(self, *_args) -> None:
        self._file.close()
        self.partial_path.unlink(missing_ok=True)


def media_extension(content_type: str) -> str:
    media_type = content_type.split(";", 1)[0].strip().lower()
    extensions = {"video/mp4": ".mp4", "video/quicktime": ".mov"}
    if media_type not in extensions:
        raise UploadError(
            "UNSUPPORTED_MEDIA_TYPE", "video/mp4 または video/quicktime を指定してください。", 415
        )
    return extensions[media_type]
